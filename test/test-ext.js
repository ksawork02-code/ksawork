const assert = require('assert');
const { makeEnv } = require('./gas-mock');
const env = makeEnv({ quiet: true }); const G = env.ctx; G.setup();
const b = (buf) => Buffer.from(buf).toString('base64');
const hwpx = { name: '신청서.hwpx', mime: '', b64: b(Buffer.concat([Buffer.from('PK\x03\x04'), Buffer.alloc(20)])) };
const hwp = { name: '신청서.hwp', mime: '', b64: b(Buffer.from([0xD0, 0xCF, 0x11, 0xE0, 1, 2, 3])) };
const fake = { name: '가짜.hwpx', mime: '', b64: hwp.b64 };
const pdf = { name: '등록증.pdf', mime: '', b64: b('%PDF-1.4') };
const co = { 사업장명: '확장자(주)', 사업자등록번호: '220-81-62517', 업태: 'a', 종목: 'b', 근로자수: '3', 사업장주소: '서울특별시 중구', 담당부서: 'x', 담당자명: 'y', 담당자직책: 'z', 담당자연락처: '010-1111-2222', 담당자이메일: 'a@b.co' };
const t = (files, re) => { try { G.submitApplication(Object.assign({}, co), files); } catch (e) { assert(re.test(e.message), e.message); console.log('  ✓ 거부:', e.message.slice(0, 70)); return; } assert.fail('no throw'); };
t({ 신청서: [hwp], 사업자등록증: [pdf] }, /\.hwp 파일은 업로드할 수 없습니다/);
t({ 신청서: [pdf], 사업자등록증: [pdf] }, /hwpx 형식만/);
t({ 신청서: [fake], 사업자등록증: [pdf] }, /올바른 HWPX/);
t({ 신청서: [hwpx], 사업자등록증: [hwp] }, /\.hwp 파일은/);
const before = Object.values(env.files).filter(f => f.getBlob).length;
assert.strictEqual(before, 0, '거부된 신청은 파일을 남기지 않음');
const r = G.submitApplication(Object.assign({}, co), { 신청서: [hwpx], 사업자등록증: [pdf] });
console.log('  ✓ hwpx + pdf 접수', r.id, '파일', Object.keys(env.files).length);
